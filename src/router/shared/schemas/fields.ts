import { z } from 'zod';
import { RegEx } from '@/lib/regex.ts';

/**
 * Общие поля форм аккаунта — ОДИН источник лимитов и текстов. Раньше каждая схема
 * задавала свои: смена ника 4–64, регистрация 3–32 («длиннее 4 см» при min 3),
 * бэк 2–32; почта при регистрации максимум 32 (не проходили длинные корпоративные
 * адреса), в смене почты — «минимум 3 бля» и никакой проверки адреса.
 * Лимиты — из правил бэка (см. ../CLAUDE.md, «Правила валидации»).
 */

export const USERNAME_MIN = 2;
export const USERNAME_MAX = 32;

export const usernameField = z
    .string()
    .min(USERNAME_MIN, { message: `Ник — минимум ${USERNAME_MIN} символа` })
    .max(USERNAME_MAX, { message: `Ник — максимум ${USERNAME_MAX} символа` })
    .regex(RegEx.USERNAME, {
        message: 'Только буквы, цифры, пробел и _, и не одни цифры'
    });

/** 254 — практический предел длины адреса (RFC 5321). */
export const emailField = z
    .string()
    .trim()
    .min(1, { message: 'Введи почту' })
    .max(254, { message: 'Слишком длинный адрес' })
    .regex(RegEx.EMAIL, { message: 'Это не похоже на адрес почты' });

/**
 * Пароль, который пользователь ЗАДАЁТ (регистрация, смена, восстановление).
 * Строгая проверка целиком: `RegEx.PASSWORD` без якорей и пропускал строку, где
 * есть 8 подходящих символов подряд (кириллица/пробелы рядом проходили).
 * Для ВХОДА не использовать — там проверяем как есть, чтобы не запереть старые пароли.
 */
const NEW_PASSWORD = /^[a-zA-Z0-9\-_=+()*&^%$#@!]{8,32}$/;

export const newPasswordField = z
    .string()
    .min(8, { message: 'Пароль должен быть не короче 8 см' })
    .max(32, { message: 'Слишком длинный пароль (мы принимаем только пароли до 32 см)' })
    .regex(NEW_PASSWORD, {
        message: 'Только латинские буквы, цифры и символы -_=+()*&^%$#@!'
    });

/** Текущий пароль для подтверждения действия: только непустой, правила проверит бэк. */
export const currentPasswordField = z.string().min(1, { message: 'Введи текущий пароль' });
